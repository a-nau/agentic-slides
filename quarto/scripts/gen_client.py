#!/usr/bin/env python3
"""Bundle the repo's browser layers into one Quarto include.

    python3 quarto/scripts/gen_client.py        # writes quarto/shim/_client.html

Every deck gets the control bar (HTML/PPTX/PDF downloads, tooltip toggle),
edit mode and comments: client-common, deck-controls, edit mode and comments
are concatenated into an include-after-body file (see _quarto.yml), after the
Marp-directive shim, so section ids exist.
The export server's port defaults to :8094; quarto/scripts/serve.py injects
DECK_API_PORT for a test instance.
"""
from pathlib import Path

Q = Path(__file__).resolve().parents[1]
SCRIPTS = Q.parent / "scripts"


def script(name: str) -> str:
    return f"<script>\n{(SCRIPTS / name).read_text()}\n</script>\n"


# Live update under quarto/scripts/serve.py: poll the page's own mtime; when the deck
# was re-rendered (an edit-pane save, an agent's edit), fetch the new HTML and
# swap only the slides that changed — no reload, so position, the edit pane and
# highlights stay. A change of slide count or <head> (new CSS) reloads instead.
# Elsewhere /__stamp 404s and it stops.
LIVE_RELOAD = """<script>
(function () {
  if (location.protocol === "file:") return;
  var p = location.pathname, last = null, base = null;
  function parse(html) {
    var doc = new DOMParser().parseFromString(html, "text/html");
    return { head: doc.head.innerHTML.replace(/\\s+/g, " "),
             slides: [].map.call(doc.querySelectorAll(".reveal .slides section.slide"), function (s) { return s.innerHTML; }) };
  }
  function load() { return fetch(p, { cache: "no-store" }).then(function (r) { return r.text(); }).then(parse); }
  function update() {
    return load().then(function (fresh) {
      var live = document.querySelectorAll(".reveal .slides section.slide");
      if (!base || fresh.slides.length !== live.length || fresh.head !== base.head) return location.reload();
      var changed = [];
      fresh.slides.forEach(function (h, i) {
        if (h !== base.slides[i]) { live[i].innerHTML = h; changed.push(live[i]); }
      });
      base = fresh;
      if (!changed.length) return;
      if (window.MarpCompat) MarpCompat.apply();
      if (window.Reveal) { if (Reveal.syncFragments) Reveal.syncFragments(); Reveal.layout(); }
      if (window.MathJax && MathJax.typesetPromise) MathJax.typesetPromise(changed).catch(function () {});
      window.dispatchEvent(new CustomEvent("deck:updated", { detail: { slides: changed } }));
    });
  }
  function tick() {
    fetch("/__stamp?p=" + encodeURIComponent(p), { cache: "no-store" })
      .then(function (r) { if (!r.ok) throw 0; return r.text(); })
      .then(function (t) {
        var next = function () { setTimeout(tick, 1000); };
        if (last !== null && t !== last && t !== "0") { last = t; return update().then(next, next); }
        last = t; next();
      })
      .catch(function () {});
  }
  load().then(function (b) { base = b; tick(); }).catch(function () {});
})();
</script>
"""


def main() -> None:
    parts = [
        script("client-common.js"),
        (SCRIPTS / "deck-controls.html").read_text(),
        "<style>\n  .bespoke-marp-osc button.dl-export.active{background:#3b82f6;color:#0a0a0a}\n</style>\n",
        script("edit-mode.js"),
        script("comments.js"),
        LIVE_RELOAD,
    ]
    out = Q / "shim" / "_client.html"
    text = "<!-- generated by quarto/scripts/gen_client.py — do not edit -->\n" + "".join(parts)
    if not out.exists() or out.read_text() != text:  # untouched file: no re-render loop
        out.write_text(text)


if __name__ == "__main__":
    main()
