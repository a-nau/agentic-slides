#!/usr/bin/env python3
"""Embed the agentic-slides logo mark into the `agentic` theme source
(themes/agentic.css; port to quarto/themes/ afterwards with
quarto/scripts/port_theme.py).

The logo is base64-embedded into the theme CSS so it renders identically in the
served decks and in PDF/HTML/PPTX export (relative url() paths don't resolve
consistently across those contexts). The PNG is a raster of assets/logo.svg
(see assets/README.md); PNG rather than SVG because the editable-PPTX exporter
re-embeds the logo as a picture.

Re-run after changing the logo. Idempotent: replaces the block between the
BRAND-ASSETS sentinels in themes/agentic.css.
"""
import base64, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOGO = ROOT / "assets" / "logo-mark.png"
THEMES = [ROOT / "themes" / "agentic.css"]

BEGIN = "/* >>> BRAND ASSETS (generated by scripts/build_brand_assets.py) >>> */"
END = "/* <<< BRAND ASSETS <<< */"

logo = "data:image/png;base64," + base64.b64encode(LOGO.read_bytes()).decode()

# The theme uses ::after for the page number. Put the logo mark on ::before
# bottom-right and move the page number to the bottom-LEFT so they never collide.
BLOCK = f"""{BEGIN}
section::before {{
  content: '';
  position: absolute;
  right: 3rem;
  bottom: 2rem;
  width: 32px;
  height: 30px;
  background-repeat: no-repeat;
  background-position: right center;
  background-size: contain;
  pointer-events: none;
  z-index: 5;
  opacity: 0.85;
  background-image: url("{logo}");
}}
section::after {{ right: auto; left: 3rem; bottom: 2rem; padding: 0; }}
{END}"""


def apply(theme_file: Path):
    css = theme_file.read_text()
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    css = pat.sub(lambda _: BLOCK, css) if pat.search(css) else css.rstrip() + "\n\n" + BLOCK + "\n"
    theme_file.write_text(css)
    print(f"  wrote {theme_file.relative_to(ROOT)} ({len(css)//1024} KB)")


for t in THEMES:
    apply(t)
