#!/usr/bin/env bash
# Build the static GitHub Pages site: every deck rendered by Quarto (in place,
# as the deck server does) and the landing pages; with SITE_EXPORTS=1 also its
# prebuilt downloads — self-contained HTML, editable PPTX and PDF, via
# scripts/export.sh. Without them the decks show no download buttons.
#
#   scripts/build_site.sh [out_dir]                  # default: _site
#   SITE_EXPORTS=1 scripts/build_site.sh [out_dir]   # + HTML/PPTX/PDF downloads
#
# Used by .github/workflows/pages.yml; runs locally too. Needs the toolchain of
# scripts/setup.sh (quarto/.dist + quarto/vendor, .venv) and rsync; with
# SITE_EXPORTS=1 also Google Chrome (PDF / PPTX exports drive it).
#
# Layout of the site (mirrors the repo, so the decks' relative links to
# ../../../quarto/themes/ resolve under a project-site sub-path too):
#   index.html                       -> decks/
#   decks/<category>/<deck>/slides.html   the rendered deck (+ images)
#   exports/<category>/<deck>.{html,editable.pptx,pdf}   (SITE_EXPORTS=1 only)
#   quarto/themes/, quarto/vendor/   theme CSS, MathJax
#   <category>/<deck>/slides.html    redirects from the pre-Quarto URLs
#
# The decks' download buttons link the prebuilt files (window.DECK_STATIC);
# edit mode and live comments need the local server and are off here.
set -euo pipefail
cd "$(dirname "$0")/.."

OUT="${1:-_site}"
EXPORTS="${SITE_EXPORTS:-0}"
OUT="${OUT%/}"
case "$OUT" in ""|.|..|decks|scripts|themes|assets|docs|quarto|exports) echo "refusing to build into '$OUT'" >&2; exit 1 ;; esac

# Every deck: decks/<category>/<deck>/slides.qmd (folders starting with . or _ are not decks).
mapfile -t DECKS < <(find decks -mindepth 3 -maxdepth 4 -name slides.qmd -not -path '*/[._]*' -printf '%h\n' | sed 's#^decks/##' | sort)

# Dates on the landing pages come from source mtimes, which a fresh checkout
# resets — take each deck source's last commit (CI checks out full history).
for d in "${DECKS[@]}"; do
    for src in "decks/$d/slides.tpl.qmd" "decks/$d/slides.qmd"; do
        [ -f "$src" ] || continue
        when=$(git log -1 --format=%cI -- "$src" 2>/dev/null || true)
        [ -z "$when" ] || touch -d "$when" "$src"
    done
done

python3 quarto/scripts/gen_client.py
quarto/scripts/render_all.sh --quiet          # every deck + the landing pages

# A deck the editable-PPTX exporter can't take (e.g. remote images) just gets
# no PPTX button; any other failed export fails the build.
[ "$EXPORTS" = 1 ] && for d in "${DECKS[@]}"; do
    echo "==> exports: $d"
    for fmt in html pdf pptx; do
        COMMENTS_HOST= scripts/export.sh "$d" "$fmt" \
            || { [ "$fmt" = pptx ] && echo "WARNING: no editable PPTX for $d (see above)" >&2; } \
            || exit 1
    done
done

rm -rf "$OUT"
mkdir -p "$OUT/decks" "$OUT/quarto"
# Rendered decks with their assets. comments.json is local review state,
# review.json holds verbatim source quotes and annotated.* are full copies of
# third-party sources (fact-check review only),
# dotfiles are tooling state.
rsync -a --no-links --exclude 'comments.json' --exclude 'review.json' --exclude 'annotated.*' --exclude '.*' \
    --exclude '__pycache__' --exclude 'export/' decks/ "$OUT/decks/"
rsync -a quarto/themes quarto/vendor "$OUT/quarto/"

for d in "${DECKS[@]}"; do
    name="$(basename "$d")"
    pptx=""
    if [ "$EXPORTS" = 1 ]; then
        mkdir -p "$OUT/exports/$(dirname "$d")"
        cp "exports/$d.html" "exports/$d.pdf" "$OUT/exports/$(dirname "$d")/"
        if [ "exports/$d.editable.pptx" -nt "decks/$d/slides.html" ]; then   # built by this run
            cp "exports/$d.editable.pptx" "$OUT/exports/$(dirname "$d")/"; pptx=1
        fi
    fi
    up="../../../exports/$(dirname "$d")/$name"   # from decks/<category>/<deck>/
    python3 - "$OUT/decks/$d/slides.html" "$up" "$EXPORTS" "$pptx" <<'PY'
import json, sys
path, up, exports, pptx = sys.argv[1:5]
# DECK_STATIC marks the static site even when empty (no buttons, no server calls)
files = {"html": up + ".html", "pdf": up + ".pdf"} if exports == "1" else {}
if pptx:
    files["pptx"] = up + ".editable.pptx"
files = json.dumps(files)
html = open(path, encoding="utf-8").read()
html = html.replace("<head>", f"<head>\n<script>window.DECK_STATIC = {files};</script>", 1)
open(path, "w", encoding="utf-8").write(html)
PY
    # the pre-Quarto URL (/<category>/<deck>/slides.html) keeps working
    mkdir -p "$OUT/$d"
    printf '<!DOCTYPE html><meta charset="utf-8"><title>moved</title><script>location.replace("../../decks/%s/slides.html" + location.hash)</script><a href="../../decks/%s/slides.html">moved here</a>\n' "$d" "$d" > "$OUT/$d/slides.html"
done

# Landing pages (generated by the render's post-render step) link the deck
# server's /…/slides.md URLs; a static host serves the rendered .html.
find "$OUT/decks" -maxdepth 2 -name index.html -exec sed -i 's#/slides\.md"#/slides.html"#g' {} +
for idx in "$OUT"/decks/*/index.html; do
    cat="$(basename "$(dirname "$idx")")"
    [ -d "$OUT/$cat" ] || continue
    printf '<!DOCTYPE html><meta charset="utf-8"><meta http-equiv="refresh" content="0; url=../decks/%s/"><a href="../decks/%s/">moved here</a>\n' "$cat" "$cat" > "$OUT/$cat/index.html"
done
printf '<!DOCTYPE html><meta charset="utf-8"><meta http-equiv="refresh" content="0; url=decks/"><title>agentic-slides</title><a href="decks/">Slide decks</a>\n' > "$OUT/index.html"
cp themes/favicon.svg "$OUT/favicon.svg"
cp LICENSE "$OUT/LICENSE.txt"   # the landing pages' footer names the license and the paper-figure exclusion
touch "$OUT/.nojekyll"   # keep _assets/ (fact-check viewer) and slides_files/ as they are
echo "Site ready in $OUT/"
